  // Filter functionality
  const filterButtons = document.querySelectorAll(".filter-btn");
  filterButtons.forEach(button => {
    button.addEventListener("click", function() {
      // Remove active class from all buttons
      filterButtons.forEach(btn => btn.classList.remove("active"));
      
      // Add active class to clicked button
      this.classList.add("active");
      
      const filter = this.dataset.filter;
      const doctorCards = document.querySelectorAll(".doctor-card");
      
      if (filter === "all") {
        doctorCards.forEach(card => {
          card.style.display = "block";
        });
      } else if (filter === "available") {
        doctorCards.forEach(card => {
          if (card.dataset.available === "true") {
            card.style.display = "block";
          } else {
            card.style.display = "none";
          }
        });
      } else {
        doctorCards.forEach(card => {
          if (card.dataset.specialization === filter) {
            card.style.display = "block";
          } else {
            card.style.display = "none";
          }
        });
      }
    });
  });

  // Compare functionality
  const compareSection = document.getElementById("compare-section");
  const compareDoctorsContainer = document.getElementById("compare-doctors");
  const compareNowBtn = document.getElementById("compare-now-btn");
  const clearCompareBtn = document.getElementById("clear-compare-btn");
  const compareButtons = document.querySelectorAll(".compare-doctor-btn");
  let comparedDoctors = [];

  compareButtons.forEach(button => {
    button.addEventListener("click", function() {
      const doctorId = this.dataset.doctorId;
      const doctorCard = this.closest(".doctor-card");
      const doctorName = doctorCard.querySelector(".top-info h2").textContent;
      const doctorImage = doctorCard.querySelector(".top-section img").src;
      
      // Check if doctor is already in compare list
      if (comparedDoctors.some(doc => doc.id === doctorId)) {
        showToast("Doctor already added to comparison");
        return;
      }
      
      // Add to compare list
      comparedDoctors.push({
        id: doctorId,
        name: doctorName,
        image: doctorImage
      });
      
      // Update UI
      updateCompareUI();
      
      // Show compare section if not visible
      compareSection.style.display = "block";
      
      showToast("Doctor added to comparison");
    });
  });

  // Clear compare list
  clearCompareBtn.addEventListener("click", function() {
    comparedDoctors = [];
    updateCompareUI();
    compareSection.style.display = "none";
    showToast("Comparison cleared");
  });

  // Compare now
  compareNowBtn.addEventListener("click", function() {
    if (comparedDoctors.length < 2) {
      showToast("Please select at least 2 doctors to compare", "error");
      return;
    }
    
    // In a real application, this would show a comparison modal
    alert(`Comparing ${comparedDoctors.length} doctors. This feature would show a detailed comparison table in a real application.`);
  });

  // Update compare UI
  function updateCompareUI() {
    compareDoctorsContainer.innerHTML = "";
    
    comparedDoctors.forEach(doctor => {
      const doctorEl = document.createElement("div");
      doctorEl.className = "compare-doctor";
      doctorEl.innerHTML = `
        <img src="${doctor.image}" alt="${doctor.name}">
        <span>${doctor.name}</span>
        <button class="remove-compare" data-id="${doctor.id}">&times;</button>
      `;
      compareDoctorsContainer.appendChild(doctorEl);
    });
    
    // Add event listeners to remove buttons
    document.querySelectorAll(".remove-compare").forEach(button => {
      button.addEventListener("click", function() {
        const id = this.dataset.id;
        comparedDoctors = comparedDoctors.filter(doc => doc.id !== id);
        updateCompareUI();
        
        if (comparedDoctors.length === 0) {
          compareSection.style.display = "none";
        }
        
        showToast("Doctor removed from comparison");
      });
    });
  }

  // Toast notification
  function showToast(message, type = "success") {
    const toast = document.getElementById("toast");
    const toastMessage = document.getElementById("toast-message");
    
    toastMessage.textContent = message;
    
    if (type === "error") {
      toast.style.background = "#dc3545";
      toast.querySelector("i").className = "fas fa-exclamation-circle";
    } else {
      toast.style.background = "#28a745";
      toast.querySelector("i").className = "fas fa-check-circle";
    }
    
    toast.classList.add("show");
    
    setTimeout(() => {
      toast.classList.remove("show");
    }, 3000);
  }

